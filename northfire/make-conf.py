#!/usr/bin/env python3
"""Northfire Services: build the Northfire config set from Anope's example configs.

Built by Kyle Bargman, 2026-11-22.

Takes data/*.example.conf (upstream Anope, with all of its documentation),
applies the Northfire network's settings and writes northfire/conf/*.conf.
Re-run it after merging a new Anope release; every change is an exact
search-and-replace, so if upstream moves something this stops with an error
instead of quietly leaving it out.

Secrets (link password, RPC token) and the opers/mail settings live in
secrets.conf and local.conf next to anope.conf on the server, never in git.
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
OUT = ROOT / "northfire" / "conf"

HEADER = (
    "/*\n"
    " * Northfire Services config - generated by northfire/make-conf.py from\n"
    " * Anope's {src}. Edit make-conf.py, not this file.\n"
    " */\n\n"
)


def edit(text, name, changes):
    """Apply (old, new) replacements; each old text must appear exactly once."""
    for old, new in changes:
        n = text.count(old)
        if n != 1:
            sys.exit(f"make-conf: {name}: expected 1 match, found {n}: {old[:70]!r}")
        text = text.replace(old, new)
    return text


ANOPE = [
    # The services server's name
    ('\tname = "services.host"\n\tvalue = "services.example.com"\n}',
     '\tname = "services.host"\n\tvalue = "services.northfire.net"\n}\n\n'
     '/* Northfire: this server\'s secrets (the uplink block with the link password,\n'
     ' * and the RPC token). Not in git; see secrets.example.conf. */\n'
     'include\n{\n\ttype = "file"\n\tname = "secrets.conf"\n}'),
    # The link to UnrealIRCd on the same machine (password from secrets.conf)
    # The uplink block (with the link password) is in secrets.conf: Anope reads
    # included files after this one, so a variable from there can't be used here.
    ('\nuplink\n{', '\n/* Northfire: the uplink block is in secrets.conf. */\n#uplink\n{'),
    ('\tpassword = "mypassword"', '\t#password = "in secrets.conf"'),
    ('\tdescription = "Anope IRC Services"',
     '\tdescription = "Services for the Northfire IRC Network"'),
    ('module { name = "inspircd" }', 'module { name = "unrealircd" }'),
    ('\tnetworkname = "LocalNet"', '\tnetworkname = "Northfire"'),
    # Logs: also to #services, and Northfire's sign-in alerts to the opers
    ('\ttarget = "services.log"\n', '\ttarget = "services.log #services"\n'),
    ('\t#target = "services.log #services"\n', ''),
    ('\tother = "expire/* bados akill/*"', '\tother = "expire/* bados akill/* nf_authguard/alert"'),
    # Passwords: Argon2id for new hashes; the old sha256 hashes still verify and
    # are re-hashed with Argon2 the next time each person signs in.
    ('module\n{\n\tname = "enc_sha2"', '#module\n{\n\tname = "enc_sha2"'),
    ('#module\n{\n\tname = "enc_argon2"', 'module\n{\n\tname = "enc_argon2"'),
    ('\t#algorithm = "argon2id"', '\talgorithm = "argon2id"'),
    ('\t#memory_cost = 131072',
     '\t/* Northfire: 19 MiB and 2 passes (OWASP\'s minimum for argon2id). Hashing runs on\n'
     '\t * services\' main thread, so a large memory_cost would stall the whole network. */\n'
     '\tmemory_cost = 19456'),
    ('\t#time_cost = 3', '\ttime_cost = 2'),
    ('#module { name = "enc_sha256" }', 'module { name = "enc_sha256" }'),
]

SUBS = {
    "botserv": [],
    "chanserv": [('\t#expire = 90d', '\texpire = 14d')],
    "global": [],
    "hostserv": [],
    "memoserv": [],
    "nickserv": [
        ('\tdefaults = "autoop hide_email hide_mask memo_receive memo_signon ns_private protect"',
         '\tdefaults = "autoop hide_email hide_mask memo_receive memo_signon ns_private"'),
        ('\texpire = 1y', '\texpire = 90d'),
        # As on the network today: registering needs no confirmation code
        ('\tregistration = "code"', '\tregistration = "none"'),
        # Needs C++20 time zones (not in Debian 12's compiler)
        ('module { name = "ns_set_timezone" }', '#module { name = "ns_set_timezone" }'),
    ],
    "operserv": [
        ('\tdefaultsessionlimit = 5', '\tdefaultsessionlimit = 3'),
        ('\t#superadmin = yes', '\tsuperadmin = yes'),
    ],
    "modules": [],
    "chanstats": [],
}

TAIL = """
/*
 * Northfire: our modules and settings, then this server's own settings (opers,
 * mail and so on; not in git, see local.example.conf).
 */
include
{
	type = "file"
	name = "northfire.conf"
}

include
{
	type = "file"
	name = "local.conf"
}
"""


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    src = (DATA / "anope.example.conf").read_text()
    text = edit(src, "anope", ANOPE)
    for sub in SUBS:
        text = text.replace(f'name = "{sub}.example.conf"', f'name = "{sub}.conf"')
    (OUT / "anope.conf").write_text(HEADER.format(src="anope.example.conf") + text + TAIL)

    for sub, changes in SUBS.items():
        src = (DATA / f"{sub}.example.conf").read_text()
        (OUT / f"{sub}.conf").write_text(HEADER.format(src=f"{sub}.example.conf") + edit(src, sub, changes))
    print("make-conf: wrote", ", ".join(sorted(p.name for p in OUT.glob("*.conf"))))


if __name__ == "__main__":
    main()
